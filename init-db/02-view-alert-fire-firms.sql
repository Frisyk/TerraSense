-- View unifying all FIRMS tables with source column
CREATE OR REPLACE VIEW monitoring.alert_fire_firms AS
SELECT 
    'Modis'::text AS source,
    uid_alert,
    latitude,
    longitude,
    brightness,
    scan,
    track,
    acq_date,
    acq_time,
    satellite,
    instrument,
    confidence::text AS confidence,
    version::text AS version,
    bright_t,
    frp,
    daynight,
    NULL::bigint AS type,
    datetm,
    date,
    wdate,
    year,
    month,
    day,
    datetm_loc,
    date_loc,
    wdate_loc,
    year_loc,
    month_loc,
    day_loc,
    date_processing,
    geometry
FROM monitoring.alert_fire_modis_raw

UNION ALL

SELECT 
    'Viirs SNPP'::text AS source,
    uid_alert,
    latitude,
    longitude,
    brightness,
    scan,
    track,
    acq_date,
    acq_time,
    satellite,
    instrument,
    confidence::text AS confidence,
    version::text AS version,
    bright_t,
    frp,
    daynight,
    type::bigint AS type,
    datetm,
    date,
    wdate,
    year,
    month,
    day,
    datetm_loc,
    date_loc,
    wdate_loc,
    year_loc,
    month_loc,
    day_loc,
    date_processing,
    geometry
FROM monitoring.alert_fire_viirssnpp_raw

UNION ALL

SELECT 
    'Viirs NOAA-20'::text AS source,
    uid_alert,
    latitude,
    longitude,
    brightness,
    scan,
    track,
    acq_date,
    acq_time,
    satellite,
    instrument,
    confidence::text AS confidence,
    version::text AS version,
    bright_t,
    frp,
    daynight,
    NULL::bigint AS type,
    datetm,
    date,
    wdate,
    year,
    month,
    day,
    datetm_loc,
    date_loc,
    wdate_loc,
    year_loc,
    month_loc,
